// Writes public/js/config.js for the shared list viewer before the build.
// The value is public: the list viewer calls the API's unauthenticated,
// token-gated shared-list endpoints from the browser.
import { writeFileSync } from 'node:fs'

const apiUrl = process.env.API_URL ?? ''

if (!/^https:\/\/[^\s/]+$/.test(apiUrl)) {
  throw new Error('Set API_URL to the https origin of the Deadwax API.')
}

const config = { apiUrl }
writeFileSync(
  new URL('../public/js/config.js', import.meta.url),
  `// Generated by scripts/write-config.mjs during the build.\nwindow.DEADWAXCLUB_CONFIG = ${JSON.stringify(config, null, 2)}\n`
)
console.log(`Wrote public/js/config.js for ${apiUrl}`)
