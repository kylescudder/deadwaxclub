// Writes public/js/config.js for the shared list viewer before the build.
// Both values are public: the anon key ships to every browser and RLS plus the
// get_shared_list* RPCs gate what it can read.
import { writeFileSync } from 'node:fs'

const supabaseUrl = process.env.SUPABASE_URL ?? ''
const supabaseAnonKey = process.env.SUPABASE_ANON_KEY ?? ''

if (!/^https:\/\/[^\s/]+$/.test(supabaseUrl)) {
  throw new Error('Set SUPABASE_URL to the https origin of the Supabase API.')
}
if (supabaseAnonKey && !/^[\w.-]{8,}$/.test(supabaseAnonKey)) {
  throw new Error('SUPABASE_ANON_KEY must be the public Supabase anon key.')
}
if (!supabaseAnonKey) {
  console.warn('SUPABASE_ANON_KEY is unset: shared lists will show an error.')
}

const config = { supabaseUrl, supabaseAnonKey }
writeFileSync(
  new URL('../public/js/config.js', import.meta.url),
  `// Generated by scripts/write-config.mjs during the build.\nwindow.DEADWAXCLUB_CONFIG = ${JSON.stringify(config, null, 2)}\n`
)
console.log(`Wrote public/js/config.js for ${supabaseUrl}`)
